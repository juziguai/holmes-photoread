/**
 * 把 TypeScript 痕迹库编译成 Skill 用的 markdown 参考文件。
 * 痕迹库的单一真源永远是 src/traces/*.ts —— 网页版和 Skill 都从这里长出来。
 * 改了痕迹库就跑 `pnpm build:skill`；忘了跑，`pnpm test` 会失败。
 */
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { REGION_LABEL, TRACES, tracesFor, type Subject, type Trace, type Weight } from '../src/traces'

const OUT_DIR = join(import.meta.dirname, '..', 'skills', 'holmes', 'references')

type Lang = 'zh' | 'en'

const W: Record<Lang, Record<Weight, string>> = {
  zh: { strong: '强', medium: '中', weak: '弱' },
  en: { strong: 'strong', medium: 'medium', weak: 'weak' },
}

const TITLE: Record<Lang, Record<Subject, string>> = {
  zh: {
    desk: '痕迹库 · 物（桌面 / 房间 / 随身物品）',
    person: '痕迹库 · 人（身上的痕迹，不是长相）',
  },
  en: {
    desk: 'Trace library · things (desk, room, everyday carry)',
    person: 'Trace library · people (the marks someone carries, never their looks)',
  },
}

const INTRO: Record<Lang, Record<Subject, string>> = {
  zh: {
    desk: '一件物品出现在这里，是因为主人做过某件事。下表是"痕迹 → 可能成因"的对照，权重是这条成因有多站得住。',
    person:
      '这里只收**人自己的选择、习惯、经历留在身上的可核对痕迹**：戴过什么、磨在哪里、晒出什么边界、多久没剃、鞋底哪侧先秃。\n\n一律不收面相骨相、族裔、健康、性取向、颜值。判据很简单：这条痕迹是他**做过的事**留下的，还是他**生下来就长这样**？后者一律不收。',
  },
  en: {
    desk: 'An object is here because its owner did something. Below: trace → the causes that could have left it, with how much weight each cause carries.',
    person:
      'This file holds only **checkable marks left by what a person chose, did, or lived through**: what they wear, where the wear is, where a tan line breaks, how long since the last shave, which edge of the sole went first.\n\nIt holds no physiognomy, no ethnicity, no health, no sexual orientation, no looks. The test is simple: did this mark come from something they **did**, or from how they were **born**? The second kind never goes in.',
  },
}

function renderTrace(lang: Lang, t: Trace): string {
  const causes = t.causes.map((c) => (lang === 'zh' ? `${c.zh}（${W.zh[c.weight]}）` : `${c.en} (${W.en[c.weight]})`)).join(lang === 'zh' ? '；' : '; ')
  const head = `- **${t.id}**${lang === 'zh' ? ' ｜ ' : ': '}${t[lang]} → ${causes}`
  const meta: string[] = []
  if (t.region) meta.push(lang === 'zh' ? `适用：${REGION_LABEL[t.region].zh}` : `applies to: ${REGION_LABEL[t.region].en}`)
  if (t.source && t.source !== 'common') meta.push(lang === 'zh' ? `出处：${t.source}` : `source: ${t.source}`)
  const metaLine = meta.length ? `\n  - ${meta.join(lang === 'zh' ? ' ｜ ' : ' · ')}` : ''
  const caution = t.caution ? `\n  - ⚠️ ${t.caution[lang]}` : ''
  return head + metaLine + caution
}

function render(lang: Lang, subject: Subject): string {
  const list = tracesFor(subject)
  const byDomain = new Map<string, Trace[]>()
  for (const t of list) {
    const arr = byDomain.get(t.domain) ?? []
    arr.push(t)
    byDomain.set(t.domain, arr)
  }
  const sections = [...byDomain.entries()]
    .map(([domain, traces]) => `## ${domain}\n\n${traces.map((t) => renderTrace(lang, t)).join('\n')}`)
    .join('\n\n')
  const footer =
    lang === 'zh'
      ? `共 ${list.length} 条。想加一条？改 \`src/traces/\`，跑 \`pnpm build:skill && pnpm test\`，提 PR。`
      : `${list.length} entries. To add one: edit \`src/traces/\`, run \`pnpm build:skill && pnpm test\`, open a PR.`
  return `<!-- Generated by \`pnpm build:skill\` from src/traces/*.ts. Edit the TypeScript, not this file. -->

# ${TITLE[lang][subject]}

${INTRO[lang][subject]}

${footer}

${sections}
`
}

export const SKILL_REFERENCES: { file: string; content: string }[] = [
  { file: 'traces-desk.md', content: render('en', 'desk') },
  { file: 'traces-person.md', content: render('en', 'person') },
  { file: 'traces-desk.zh.md', content: render('zh', 'desk') },
  { file: 'traces-person.zh.md', content: render('zh', 'person') },
]

/** 供测试用：生成物和磁盘上的文件是否一致 */
export function checkSkillReferencesFresh(): string[] {
  const stale: string[] = []
  for (const { file, content } of SKILL_REFERENCES) {
    const path = join(OUT_DIR, file)
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) stale.push(file)
  }
  return stale
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  for (const { file, content } of SKILL_REFERENCES) {
    writeFileSync(join(OUT_DIR, file), content, 'utf8')
    console.log(`wrote references/${file}`)
  }
  console.log(`痕迹库共 ${TRACES.length} 条：物 ${tracesFor('desk').length}，人 ${tracesFor('person').length}`)
}
